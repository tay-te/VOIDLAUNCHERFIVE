package dev.voidmc.lod.source;

import dev.voidmc.expanse.registry.LandformBlocks;
import dev.voidmc.expanse.world.terrain.Column;
import dev.voidmc.expanse.world.terrain.EarthChunkGenerator;
import dev.voidmc.expanse.world.terrain.Landform;
import dev.voidmc.expanse.world.terrain.TerrainModel;
import dev.voidmc.lod.core.ColumnSample;
import dev.voidmc.lod.core.Colors;
import net.minecraft.core.Holder;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.biome.Biome;
import net.minecraft.world.level.block.Blocks;

/**
 * The fast path for Expanse's Earth worlds: the terrain model answers a column (ground height, rivers,
 * crater lakes, landform, climate) in a couple of microseconds, against the tens a generic noise walk
 * costs, so the whole horizon can be built before a player has finished looking at it.
 *
 * <p>Everything the model knows shows up at a distance: rivers are cut to their own water level and carry
 * it across the plate (and still show as a thread of water where they are narrower than a cell), crater
 * lakes and lava fill volcano tops, canyon walls carry the world's own strata, salt flats are white, and
 * snow lies where the biome's own temperature, falling with height, lays it in the chunks, so a mountain range is
 * white at the top for the same reason in the LOD as in the chunks. Above the tree line young
 * ranges are bare rock, the forest thinning out below it rather than stopping at a contour.
 *
 * <p>Only loaded when Expanse is: nothing else references this class.
 */
public final class ExpanseSource extends WorldgenSource {
	private final TerrainModel model;
	private final int salt;
	private final int ash;
	private final int basalt;

	private ExpanseSource(ServerLevel level, TerrainModel model, long version, Materials materials) {
		super(level, version, materials);
		this.model = model;
		this.salt = this.looks.colorOf(LandformBlocks.SALT_BLOCK.defaultBlockState());
		this.ash = this.looks.colorOf(LandformBlocks.VOLCANIC_ASH.defaultBlockState());
		this.basalt = this.looks.colorOf(Blocks.BASALT.defaultBlockState());
	}

	@Override
	public String diagnostics() {
		return ", Earth plates built " + TerrainModel.BUILDS.get();
	}

	/** The Earth source for a level, or null if the level is not generated by Expanse's Earth terrain. */
	public static WorldgenSource tryCreate(ServerLevel level, long version, Materials materials) {
		if (level.getChunkSource().getGenerator() instanceof EarthChunkGenerator earth) {
			return new ExpanseSource(level, earth.model(level.getChunkSource().randomState()), version, materials);
		}
		return null;
	}

	@Override
	public void sample(int x, int z, int cell, ColumnSample out) {
		if (!TIMING) {
			this.sample(x, z, cell, out, 0);
			return;
		}
		long t0 = System.nanoTime();
		this.sample(x, z, cell, out, t0);
		TIMES.addAndGet(2, System.nanoTime() - t0);
	}

	private void sample(int x, int z, int cell, ColumnSample out, long t0) {
		// Read everything from the column before anything else samples the model: its column is reused.
		Column c = this.model.sample(x, z);
		if (TIMING) {
			TIMES.addAndGet(0, System.nanoTime() - t0);
		}
		float ground = c.height;
		int water = Integer.MIN_VALUE;
		boolean lava = false;
		// A river narrower than most of a cell is drawn as the share of the cell it covers, at the valley floor's
		// height, not as water at the one vertex that happens to fall in it: otherwise far rivers are a dotted
		// line, or a groove whose walls catch the light.
		boolean narrow = cell > 1 && 2 * c.riverHalfWidth < 1.5F * cell;
		if (c.inChannel() && !narrow) {
			water = c.waterTop();
			ground = Math.min(ground, c.bed());
		} else if (c.fjord || Math.ceil(ground) < this.seaLevel) {
			water = this.seaLevel;
		}
		if (c.crater > ground) {
			water = Math.max(water, (int) Math.ceil(c.crater));
			lava = c.craterLava;
		}
		int landform = c.landform;
		float coast = c.coast;
		float uplift = c.uplift;
		// a river narrower than the cell still shows, as the share of the cell it covers
		float river = 0;
		if (water == Integer.MIN_VALUE && c.nearRiver() && cell > 1) {
			float reach = c.riverHalfWidth + cell * 0.5F - c.riverDist;
			river = Math.max(0, Math.min(1, reach / cell)) * Math.min(1, 0.4F + 2 * c.riverHalfWidth / cell);
		}
		int top = (int) Math.ceil(ground);

		long t2 = TIMING ? System.nanoTime() : 0;
		Holder<Biome> biome = this.biome(x, Math.max(top, this.seaLevel), z, cell);
		if (TIMING) {
			TIMES.addAndGet(1, System.nanoTime() - t2);
		}
		BiomeLooks.Look look = this.looks.get(biome);
		look.fill(out);
		out.ground = ground;
		out.water = water;
		out.lava = lava;
		if (lava) {
			out.waterColor = this.looks.lava;
		}
		this.strata(x, z, out);
		if (out.bands != null) {
			out.side = ColumnSample.rockAt(out.bands, out.bandHeight, out.rock, top - 1 + out.bandOffset);
		}
		boolean wet = water != Integer.MIN_VALUE && water > ground;
		if (wet) {
			out.top = look.bed();
			out.canopy = 0;
			out.cover = 0;
			return;
		}

		switch (landform) {
			case Landform.SALT_FLAT -> {
				out.top = out.side = out.soil = this.salt;
				out.cover = 0;
			}
			case Landform.VOLCANIC -> {
				out.top = Colors.mix(this.basalt, this.ash, 0.4F);
				out.side = out.soil = out.rock = this.basalt;
				out.cover = 0;
			}
			default -> {
			}
		}
		if (landform == Landform.NONE || landform == Landform.FJORD || landform == Landform.TEPUI) {
			// snow where the chunks will lay it: the biome's own temperature at this height
			float snow = this.snow(biome, x, top, z, cell);
			// bare rock above the tree line on high, young ranges
			float bare = Colors.smooth(135, 175, top) * Colors.smooth(0.95F, 1.25F, uplift);
			if (look.ground() == BiomeLooks.Ground.GRASS || look.ground() == BiomeLooks.Ground.PODZOL) {
				out.top = Colors.mix(out.top, this.looks.stone, bare * 0.9F);
				out.side = Colors.mix(out.side, this.looks.stone, bare);
				if (top <= this.seaLevel + 2 && coast < 48) {
					// beaches
					float beach = Colors.smooth(48, 20, coast);
					out.top = Colors.mix(out.top, this.looks.sand, beach);
					out.side = Colors.mix(out.side, this.looks.sand, beach);
				}
			}
			if (snow > 0 && look.ground() != BiomeLooks.Ground.SNOWCAP) {
				out.top = Colors.mix(out.top, this.looks.snowTop, snow);
				out.side = Colors.mix(out.side, this.looks.snowSide, snow * 0.8F);
				// snow on the boughs
				}
			out.cover *= 1 - bare;
		}
		if (river > 0) {
			int surface = Colors.water(out.waterColor, look.bed(), 2, false);
			out.top = Colors.mix(out.top, surface, river);
			out.cover *= 1 - river;
		}
	}
}
