#!/usr/bin/env node
/**
 * The cosmetics pipeline, from `schema/cosmetics.json` and `mod/src/main/cosmetics-src/` to
 * everything that ships:
 *
 *  1. **Java catalog** — `mod/src/main/java/dev/voidpvp/client/cosmetic/CosmeticCatalog.java`,
 *     the id → kind/name/rarity/tint table the mod reads. Same split as `gen-java-registry.mjs`:
 *     only the data is generated; the few lines of machinery live in the template below.
 *  2. **TypeScript catalog** — `packages/protocol/src/generated/cosmetics.ts`, exported from
 *     `@void/protocol` for the launcher Store and the in-game wardrobe.
 *  3. **Runtime assets** — every item's source folder `mod/src/main/cosmetics-src/<id>/` is
 *     compiled into `mod/src/main/resources/assets/void/cosmetics/<id>/`: the source model (a
 *     Blockbench-style cuboid/bone/keyframe JSON, see `docs/cosmetics.md`) becomes a compact,
 *     validated runtime `model.json` with every face's UV resolved; PNG layers are checked for
 *     size and copied; emote and trail descriptors are validated and minified.
 *
 * All three outputs are COMMITTED, for the reason `gen-java-registry.mjs` gives at length:
 * there is no Node on the Gradle path, so a file the jar needs cannot be a build artefact of a
 * Node script. `--check` is the gate that the committed copies are still their sources.
 *
 *   node scripts/gen-cosmetics.mjs           # write everything
 *   node scripts/gen-cosmetics.mjs --check   # exit 1 if anything is stale or missing
 *
 * The sources themselves (textures and models) are painted by `mod/cosmetics-art/paint.mjs`;
 * they are committed too, so an artist can open one in Blockbench or an image editor and this
 * script never needs the painter.
 */

