/* Write or check                                                                             */
/* ------------------------------------------------------------------------------------------ */

if (problems.length) {
  console.error(`gen-cosmetics: ${problems.length} problem(s):\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

const same = (path, content) => {
  if (!existsSync(path)) return false;
  const have = readFileSync(path);
  if (Buffer.isBuffer(content)) return have.equals(content);
  // Text compares line-ending blind: a Windows checkout with autocrlf holds CRLF copies of
  // files this script writes with LF, and that is not staleness.
  const lf = (t) => t.split('\r\n').join('\n');
  return lf(have.toString('utf8')) === lf(content);
};

// Stale assets: anything under ASSET_DIR this run would not produce.
const stale = [];
const walk = (d) => {
  if (!existsSync(d)) return;
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (!outputs.has(p)) stale.push(p);
  }
};
walk(ASSET_DIR);

if (CHECK) {
  const bad = [...outputs].filter(([p, c]) => !same(p, c)).map(([p]) => relative(ROOT, p));
  bad.push(...stale.map((p) => `${relative(ROOT, p)} (stale)`));
  if (bad.length) {
    console.error(`gen-cosmetics --check: ${bad.length} file(s) out of date — run \`node scripts/gen-cosmetics.mjs\`:\n  ${bad.join('\n  ')}`);
    process.exit(1);
  }
  console.log(`gen-cosmetics --check: ok (${ITEMS.length} items, ${outputs.size} files)`);
} else {
  for (const p of stale) rmSync(p);
  let wrote = 0;
  for (const [p, c] of outputs) {
    if (same(p, c)) continue;
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, c);
    wrote += 1;
  }
  console.log(`gen-cosmetics: ${ITEMS.length} items, ${outputs.size} files (${wrote} written, ${stale.length} removed)`);
}
