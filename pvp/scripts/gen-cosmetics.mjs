/** Reads width/height out of a PNG's IHDR, refusing anything that is not one. */
function pngSize(buf, where) {
  const sig = '89504e470d0a1a0a';
  if (buf.length < 24 || buf.subarray(0, 8).toString('hex') !== sig) {
    problems.push(`${where}: not a PNG`);
    return [0, 0];
  }
  return [buf.readUInt32BE(16), buf.readUInt32BE(20)];
}

const r4 = (n) => Math.round(n * 1e4) / 1e4;
const DEG = Math.PI / 180;
const EASES = ['linear', 'step', 'sine', 'quad', 'cubic', 'back', 'elastic', 'bounce'];

/**
 * Resolves Minecraft box UV into per-face rects — the exact layout `ModelBox` uses, in the face
 * conventions `CosmeticModel.java` draws with (see docs/cosmetics.md, "Face UV").
 */
function boxUv(u, v, w, h, d) {
  return {
    e: [u + d + w, v + d, u + d + w + d, v + d + h],
    w: [u, v + d, u + d, v + d + h],
    u: [u + d, v, u + d + w, v + d],
    d: [u + d + w, v, u + d + w + w, v + d],
    n: [u + d, v + d, u + d + w, v + d + h],
    s: [u + d + w + d, v + d, u + d + w + d + w, v + d + h],
  };
}

const FACE_ALIASES = { north: 'n', south: 's', east: 'e', west: 'w', up: 'u', down: 'd' };

/**
 * Materials, in the runtime's index order (`CosmeticShader.MATERIALS`): how the material shader
 * lights a part. A cube takes its own `material`, else its bone's, else the model's, else matte.
 */
const MATERIALS = ['matte', 'cloth', 'metal', 'glass', 'emissive'];

function materialIndex(name, where) {
  if (name == null) return null;
  const i = MATERIALS.indexOf(name);
  if (i < 0) problems.push(`${where}: unknown material ${name} (one of ${MATERIALS.join(', ')})`);
  return i < 0 ? 0 : i;
}

function compileModel(id, src, tex, where) {
  const bones = src.bones ?? [];
  const index = new Map(bones.map((b, i) => [b.name, i]));
  if (index.size !== bones.length) problems.push(`${where}: duplicate bone names`);
  const modelMat = materialIndex(src.material, where) ?? 0;
  const outBones = bones.map((b) => {
    const boneMat = materialIndex(b.material, `${where}: ${b.name}`) ?? modelMat;
    const parent = b.parent == null ? -1 : index.get(b.parent);
    if (parent === undefined) problems.push(`${where}: bone ${b.name} has unknown parent ${b.parent}`);
    const cubes = (b.cubes ?? []).map((c, ci) => {
      const [x0, y0, z0] = c.from;
      const [x1, y1, z1] = c.to;
      if (!(x1 >= x0 && y1 >= y0 && z1 >= z0)) problems.push(`${where}: ${b.name} cube ${ci} has from > to`);
      let faces;
      if (c.uv) {
        const size = c.uv_size ?? [x1 - x0, y1 - y0, z1 - z0].map((s) => Math.round(s));
        faces = boxUv(c.uv[0], c.uv[1], size[0], size[1], size[2]);
        if (c.mirror) for (const k of Object.keys(faces)) faces[k] = [faces[k][2], faces[k][1], faces[k][0], faces[k][3]];
      } else {
        faces = {};
        for (const [name, rect] of Object.entries(c.faces ?? {})) faces[FACE_ALIASES[name] ?? name] = rect;
      }
      // Zero-area faces of a flat plane are dropped; faces with a null rect are left undrawn.
      const area = { n: (x1 - x0) * (y1 - y0), s: (x1 - x0) * (y1 - y0), e: (z1 - z0) * (y1 - y0),
        w: (z1 - z0) * (y1 - y0), u: (x1 - x0) * (z1 - z0), d: (x1 - x0) * (z1 - z0) };
      const f = {};
      for (const [k, rect] of Object.entries(faces)) {
        if (!rect || !(k in area)) continue;
        if (area[k] <= 0) continue;
        for (const n of rect) if (n < 0 || n > Math.max(tex[0], tex[1])) problems.push(`${where}: ${b.name} cube ${ci} face ${k} uv ${rect} outside the texture`);
        if (rect[0] > tex[0] || rect[2] > tex[0] || rect[1] > tex[1] || rect[3] > tex[1]) problems.push(`${where}: ${b.name} cube ${ci} face ${k} uv ${rect} outside ${tex}`);
        f[k] = rect.map(r4);
      }
      const out = { f: [x0, y0, z0, x1, y1, z1].map(r4), uv: f };
      if (c.inflate) out.i = r4(c.inflate);
      if (c.layer) out.l = c.layer; // "albedo" (default) or "emissive-only"
      const m = materialIndex(c.material, `${where}: ${b.name} cube ${ci}`) ?? boneMat;
      if (m) out.m = m;
      return out;
    });
    const o = { n: b.name, p: parent, pv: (b.pivot ?? [0, 0, 0]).map(r4), r: (b.rotation ?? [0, 0, 0]).map((d) => r4(d * DEG)) };
    if (cubes.length) o.c = cubes;
    if (b.billboard) o.bb = 1;
    return o;
  });

  const glow = (src.glow ?? []).map((g) => {
    const bi = index.get(g.bone);
    if (bi === undefined) problems.push(`${where}: glow on unknown bone ${g.bone}`);
    return [bi ?? 0, ...g.at.map(r4), parseInt(g.color.slice(1), 16), r4(g.size ?? 3), r4(g.strength ?? 0.5)];
  });

  const anims = {};
  for (const [name, a] of Object.entries(src.animations ?? {})) {
    const ch = [];
    for (const [bone, chans] of Object.entries(a.bones ?? {})) {
      const bi = index.get(bone);
      if (bi === undefined) { problems.push(`${where}: animation ${name} drives unknown bone ${bone}`); continue; }
      for (const [prop, keys] of Object.entries(chans)) {
        if (!['rotation', 'position', 'scale'].includes(prop)) { problems.push(`${where}: ${name}.${bone}: unknown channel ${prop}`); continue; }
        ch.push([bi, prop[0], compileKeys(keys, prop === 'rotation', `${where}: ${name}.${bone}.${prop}`)]);
      }
    }
    anims[name] = { len: r4(a.length), loop: a.loop ? 1 : 0, ch };
  }

  const out = { v: 1, attach: src.attach ?? 'body', tex, bones: outBones };
  if (src.procedural) out.proc = src.procedural;
  // Motion personality for the procedural rig: how fast and how far the wings beat, as
  // multiples of the shared defaults (a toy flutters, a blade barely stirs).
  if (src.motion) {
    const mo = [src.motion.rate ?? 1, src.motion.amp ?? 1];
    if (mo.some((k) => !(k >= 0.25 && k <= 3))) problems.push(`${where}: motion rate/amp must be within 0.25..3`);
    out.mo = mo.map(r4);
  }
  if (src.helmet_fit !== undefined) out.fit = src.helmet_fit;
  if (glow.length) out.glow = glow;
  if (Object.keys(anims).length) out.anims = anims;
  return out;
}

function compileKeys(keys, degrees, where) {
  let last = -1;
  return keys.map((k) => {
    const [t, val, ease = 'sine'] = k;
    if (t < last) problems.push(`${where}: keyframes out of order at ${t}`);
    last = t;
    if (!EASES.includes(ease)) problems.push(`${where}: unknown ease ${ease}`);
    const v = degrees ? val.map((d) => r4(d * DEG)) : val.map(r4);
    return [r4(t), ...v, EASES.indexOf(ease)];
  });
}

/** Player parts an emote may drive, and the root (a whole-body transform). */
const EMOTE_PARTS = ['root', 'upper', 'head', 'body', 'right_arm', 'left_arm', 'right_leg', 'left_leg'];

function compileEmote(src, where) {
  const ch = [];
  for (const [part, chans] of Object.entries(src.parts ?? {})) {
    const pi = EMOTE_PARTS.indexOf(part);
    if (pi < 0) { problems.push(`${where}: unknown part ${part}`); continue; }
    for (const [prop, keys] of Object.entries(chans)) {
      if (!['rotation', 'position'].includes(prop)) { problems.push(`${where}: ${part}: unknown channel ${prop}`); continue; }
      ch.push([pi, prop[0], compileKeys(keys, prop === 'rotation', `${where}: ${part}.${prop}`)]);
    }
  }
  const out = { v: 1, len: r4(src.length), loop: src.loop ? 1 : 0, blend: r4(src.blend ?? 0.25), ch };
  if (src.loop_from !== undefined) out.loopFrom = r4(src.loop_from);
  if (src.camera) out.cam = src.camera;
  return out;
}

const TRAIL_MOTIONS = ['spark', 'drift', 'settle', 'stair'];

function compileTrail(src, where) {
  if (!TRAIL_MOTIONS.includes(src.motion)) problems.push(`${where}: unknown motion ${src.motion}`);
  const hex = (h) => parseInt(h.slice(1), 16);
  return {
    v: 1, motion: src.motion, colors: (src.colors ?? []).map(hex), life: r4(src.life ?? 1),
    rate: r4(src.rate ?? 12), size: r4(src.size ?? 0.12), cap: src.cap ?? 32, glow: r4(src.glow ?? 0),
    frames: src.frames ?? 1,
  };
}

/** Which source files each kind must have, and what to make of them. */
const REQUIRED = {
  cape: ['cape.json', 'texture.png'],
  back: ['model.json', 'texture.png'],
  head: ['model.json', 'texture.png'],
  face: ['model.json', 'texture.png'],
  halo: ['model.json', 'texture.png'],
  trail: ['trail.json', 'sprite.png'],
  badge: ['badge.json', 'icon.png'],
  emote: ['emote.json'],
};

for (const item of ITEMS) {
  const dir = join(SRC_DIR, item.id);
  const out = join(ASSET_DIR, item.id);
  const where = relative(ROOT, dir).replaceAll('\\', '/');
  if (!existsSync(dir)) { problems.push(`${where}: missing — every catalog item needs bundled assets`); continue; }
  for (const req of REQUIRED[item.kind]) if (!existsSync(join(dir, req))) problems.push(`${where}/${req}: missing`);
  const files = readdirSync(dir).filter((f) => statSync(join(dir, f)).isFile());
  let texSize = null;
  let frames = 1;
  const meta = files.includes('cape.json') ? JSON.parse(readFileSync(join(dir, 'cape.json'), 'utf8'))
    : files.includes('badge.json') ? JSON.parse(readFileSync(join(dir, 'badge.json'), 'utf8')) : null;
  const pngSizes = {};
  for (const f of files.filter((f) => f.endsWith('.png'))) {
    const buf = readFileSync(join(dir, f));
    const [w, h] = pngSize(buf, `${where}/${f}`);
    pngSizes[f] = [w, h];
    if (f === 'texture.png' || f === 'icon.png') texSize = [w, h];
    outputs.set(join(out, f), buf);
  }
  // A material mask is the texture's width and either one frame or the whole strip tall.
  if (pngSizes['material.png'] && texSize) {
    const [mw, mh] = pngSizes['material.png'];
    if (mw !== texSize[0] || texSize[1] % mh !== 0) problems.push(`${where}/material.png: ${mw}x${mh} does not match texture.png ${texSize}`);
  }
  if (files.includes('model.json')) {
    const src = JSON.parse(readFileSync(join(dir, 'model.json'), 'utf8'));
    const tex = src.texture_size ?? texSize;
    frames = src.frames?.count ?? 1;
    if (texSize && (texSize[0] !== tex[0] || texSize[1] !== tex[1] * frames)) problems.push(`${where}: texture.png is ${texSize}, model says ${tex} x ${frames} frames`);
    const model = compileModel(item.id, src, tex, `${where}/model.json`);
    if (src.frames) model.frames = [frames, src.frames.fps ?? 8];
    outputs.set(join(out, 'model.json'), JSON.stringify(model));
  }
  if (files.includes('cape.json')) {
    // A cape is cloth, not a model: the descriptor only says how its texture animates and how
    // the cloth should feel. The layout is the vanilla 64 x 32 cape layout, at any multiple.
    const c = meta;
    frames = c.frames?.count ?? 1;
    if (texSize) {
      const k = texSize[0] / 64;
      if (!Number.isInteger(k) || texSize[1] !== 32 * k * frames) problems.push(`${where}: cape texture ${texSize} is not 64x32 x ${frames} frames at an integer scale`);
    }
    const capeOut = {
      v: 1, frames: [frames, c.frames?.fps ?? 8], stiffness: c.stiffness ?? 0.9, weight: c.weight ?? 1,
      glow: (c.glow ?? []).map((g) => [r4(g.at[0]), r4(g.at[1]), parseInt(g.color.slice(1), 16), r4(g.size ?? 3), r4(g.strength ?? 0.4)]),
    };
    // The sheet's material where material.png says nothing; cloth unless the cape says otherwise.
    const cm = materialIndex(c.material ?? 'cloth', `${where}/cape.json`);
    if (cm !== 1) capeOut.m = cm;
    outputs.set(join(out, 'cape.json'), JSON.stringify(capeOut));
  }
  if (files.includes('badge.json')) {
    outputs.set(join(out, 'badge.json'), JSON.stringify({ v: 1, frames: [meta.frames?.count ?? 1, meta.frames?.fps ?? 4], glow: meta.glow ?? 0 }));
  }
  if (files.includes('emote.json')) {
    outputs.set(join(out, 'emote.json'), JSON.stringify(compileEmote(JSON.parse(readFileSync(join(dir, 'emote.json'), 'utf8')), `${where}/emote.json`)));
  }
  if (files.includes('trail.json')) {
    outputs.set(join(out, 'trail.json'), JSON.stringify(compileTrail(JSON.parse(readFileSync(join(dir, 'trail.json'), 'utf8')), `${where}/trail.json`)));
  }
}

// Source folders that no catalog item names are a mistake in one direction or the other.
if (existsSync(SRC_DIR)) {
  for (const d of readdirSync(SRC_DIR)) {
    if (statSync(join(SRC_DIR, d)).isDirectory() && !ITEMS.some((i) => i.id === d)) problems.push(`cosmetics-src/${d}: no catalog item has this id`);
  }
}

// An index of every bundled id, so the runtime can enumerate without listing a jar directory.
outputs.set(join(ASSET_DIR, 'index.json'), JSON.stringify({ v: catalog.version, ids: ITEMS.map((i) => i.id) }));

