/**
 * The dot-matrix watermark behind the Play stage.
 *
 * `design/screens/launcher/Launcher-Play.png` fills the content panel with a sparse
 * field of cells — 10 × 10 at a 3px radius on a 28px step, from (48, 96) to (1532,
 * 824) in window coordinates, 54 columns by 27 rows — whose alpha ramps from ~.023 on
 * the left to ~.078 on the right. It is the VOID mark drawn in cells, and it is the
 * only thing between the hero and an empty box: without it the stage reads as a
 * 1536 × 768 hole rather than as a surface.
 *
 * The matrix below is the frame's own, read back off the PNG cell by cell (sample the
 * centre of each 10px cell; anything above the panel fill and below UI ink is a cell),
 * with the status chip and the dock card masked out because they cover part of the
 * field. 536 of the 1458 slots are lit.
 *
 * It is data, not art: nothing here is invented, and re-reading the frame regenerates
 * it exactly.
 */

/** Cell edge, in px. */
export const WM_CELL = 10;
/**
 * The mark's own cell edge. The field has two layers: the 10px scatter, and a second
 * pass of 28px cells — one grid slot each, so they abut — that spell the VOID ring.
 * That ring is what makes the field read as a watermark rather than as noise.
 */
export const WM_MARK_CELL = 28;
/** Distance between two cells' left edges, in px. */
export const WM_STEP = 28;
/** Where the first cell sits, relative to the content panel's padding box. */
export const WM_ORIGIN = { x: 15, y: 15 };
/** The alpha the leftmost and rightmost columns are drawn at. */
export const WM_ALPHA = { from: 0.023, to: 0.078 };
/** The mark's cells sit ~1.4x above the scatter at the same column. */
export const WM_MARK_GAIN = 1.4;

