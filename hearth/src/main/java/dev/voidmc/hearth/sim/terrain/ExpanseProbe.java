package dev.voidmc.hearth.sim.terrain;

import dev.voidmc.expanse.world.terrain.Column;
import dev.voidmc.expanse.world.terrain.EarthChunkGenerator;
import dev.voidmc.expanse.world.terrain.TerrainModel;
import dev.voidmc.hearth.api.TerrainProbe;
import net.minecraft.server.level.ServerLevel;
import org.jspecify.annotations.Nullable;

/**
 * The fast path for Expanse's Earth worlds: the terrain model answers a column (ground, rivers with their own water
 * level, coasts, crater lakes, climate with the lapse rate) in a couple of microseconds against the tens a noise walk
 * costs, which is what lets the atlas survey a region and a history plan a town in a fraction of a second.
 *
 * <p>Only loaded when Expanse is: {@link Probes} is the one place that names it, behind {@code isModLoaded("expanse")},
 * and {@link #tryCreate} returns the interface type so callers never need the class resolved.
 */
public final class ExpanseProbe extends GeneratorProbe {
	private final TerrainModel model;

	private ExpanseProbe(ServerLevel level, TerrainModel model) {
		super(level);
		this.model = model;
	}

	/** The Earth probe for a level, or null if the level is not generated by Expanse's Earth terrain. */
	public static @Nullable TerrainProbe tryCreate(ServerLevel level) {
		if (level.getChunkSource().getGenerator() instanceof EarthChunkGenerator earth) {
			return new ExpanseProbe(level, earth.model(level.getChunkSource().randomState()));
		}
		return null;
	}

	@Override
	protected void compute(int x, int z, Sample out) {
		// read everything before anything else samples the model: its column object is reused
		Column c = this.model.sample(x, z);
		int ground = (int) Math.ceil(c.height);
		int water = NO_WATER;
		if (c.inChannel()) {
			water = c.waterTop();
			ground = Math.min(ground, c.bed());
		} else if (c.fjord || ground < this.seaLevel) {
			water = this.seaLevel;
		}
		if (c.crater > ground) {
			// a crater lake (or lava): not ground anyone builds on
			water = Math.max(water, (int) Math.ceil(c.crater));
		}
		out.ground = ground;
		out.water = water;
		out.temperature = c.temperature;
	}

	@Override
	public String describe() {
		return "Expanse terrain model";
	}
}
