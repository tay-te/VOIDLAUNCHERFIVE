package dev.voidmc.hearth.sim.terrain;

import dev.voidmc.expanse.world.terrain.Column;
import dev.voidmc.expanse.world.terrain.EarthChunkGenerator;
import dev.voidmc.expanse.world.terrain.TerrainModel;
import dev.voidmc.hearth.api.TerrainProbe;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.levelgen.Heightmap;
import org.jspecify.annotations.Nullable;

/**
 * The fast path for Expanse's Earth worlds: the terrain model answers a column (ground, rivers with their own water
 * level, coasts, crater lakes) in a couple of microseconds against the hundreds a noise walk
 * costs, which is what lets the atlas survey a region and a history plan a town in a fraction of a second.
 *
 * <p>The model's height is the surface before the generator adds its 3D noise and interpolates density between 4 × 8
 * cells, which moves the real ground a block or two (more on steep ground). Foundations need the real ground, so the
 * probe measures that difference with the generator itself on an 8-block grid and adds it back, interpolated: one noise
 * walk per 64 columns buys a little accuracy (measured on one seed: 92% of columns within a block of the real ground
 * uncorrected, 94% corrected) while rivers, banks and coasts keep the model's full detail. It costs several times the
 * model alone, so it is off unless {@code probe_correction} is set; the site survey always uses the {@link #rough} view.
 *
 * <p>Only loaded when Expanse is: {@link Probes} is the one place that names it, behind {@code isModLoaded("expanse")},
 * and {@link #tryCreate} returns the interface type so callers never need the class resolved.
 */
public final class ExpanseProbe extends GeneratorProbe {
	private static final int GRID = 8;
	private static final int CORNERS = 1 << 12;
	/** Corrections beyond this are cave mouths or overhangs, not the surface: ignored. */
	private static final int MAX_CORRECTION = 5;

	private final TerrainModel model;
	private final ThreadLocal<CornerCache> corners = ThreadLocal.withInitial(CornerCache::new);
	private final GeneratorProbe rough;
	private final boolean correct;

	private ExpanseProbe(ServerLevel level, TerrainModel model, boolean correct) {
		super(level);
		this.model = model;
		this.correct = correct;
		ExpanseProbe self = this;
		this.rough = new GeneratorProbe(level) {
			@Override
			protected void compute(int x, int z, Sample out) {
				self.modelColumn(x, z, out);
			}

			@Override
			public String describe() {
				return "Expanse terrain model (uncorrected)";
			}
		};
	}

	/** The Earth probe for a level, or null if the level is not generated by Expanse's Earth terrain. */
	public static @Nullable TerrainProbe tryCreate(ServerLevel level, boolean correct) {
		if (level.getChunkSource().getGenerator() instanceof EarthChunkGenerator earth) {
			return new ExpanseProbe(level, earth.model(level.getChunkSource().randomState()), correct);
		}
		return null;
	}

	@Override
	public GeneratorProbe rough() {
		return this.rough;
	}

	private static final class CornerCache {
		final long[] keys = new long[CORNERS];
		final float[] values = new float[CORNERS];

		CornerCache() {
			java.util.Arrays.fill(this.keys, Long.MIN_VALUE);
		}
	}

	/** The model's own answer: ground, water and temperature. Returns whether the column is in or by a river. */
	private boolean modelColumn(int x, int z, Sample out) {
		// read everything before anything else samples the model: its column object is reused
		Column c = this.model.sample(x, z);
		int ground = (int) Math.ceil(c.height);
		int water = NO_WATER;
		boolean river = c.nearRiver() && !c.fjord && c.riverDist < c.riverHalfWidth + 3;
		if (c.inChannel()) {
			water = c.waterTop();
			ground = Math.min(ground, c.bed());
		} else if (c.fjord || ground < this.seaLevel) {
			water = this.seaLevel;
		}
		if (c.crater > ground) {
			// a crater lake (or lava): not ground anyone builds on
			water = Math.max(water, (int) Math.ceil(c.crater));
		}
		if (c.lake > -900 && c.lakeEdge > 0) {
			// an ordinary lake in a lowland hollow or a tarn up high: its shore ring (lakeEdge < 0) is dry ground at lake + 1
			water = Math.max(water, (int) c.lake + 1);
		}
		out.ground = ground;
		out.water = water;
		// the model's temperature is the biome source's climate parameter, not a biome temperature: leave it to the biome
		return river || water != NO_WATER;
	}

	@Override
	protected void compute(int x, int z, Sample out) {
		boolean wet = modelColumn(x, z, out);
		if (wet || !this.correct) {
			// river beds, banks and the sea floor are the model's own: the generator pours them exactly so
			return;
		}
		int x0 = Math.floorDiv(x, GRID) * GRID;
		int z0 = Math.floorDiv(z, GRID) * GRID;
		float fx = (x - x0) / (float) GRID;
		float fz = (z - z0) / (float) GRID;
		float sum = 0;
		float weight = 0;
		for (int i = 0; i < 4; i++) {
			int cx = x0 + (i & 1) * GRID;
			int cz = z0 + (i >> 1) * GRID;
			float c = correction(cx, cz);
			if (Float.isNaN(c)) {
				continue;
			}
			float w = ((i & 1) == 1 ? fx : 1 - fx) * ((i >> 1) == 1 ? fz : 1 - fz);
			sum += c * w;
			weight += w;
		}
		if (weight > 0.05F) {
			out.ground += Math.round(sum / weight);
		}
	}

	/** Real ground minus model ground at a grid corner, or NaN where it says nothing about the surface. */
	private float correction(int x, int z) {
		CornerCache cache = this.corners.get();
		long key = (long) x << 32 ^ z & 0xFFFF_FFFFL;
		int slot = (int) ((key * 0x9E3779B97F4A7C15L) >>> 52) & (CORNERS - 1);
		if (cache.keys[slot] == key) {
			return cache.values[slot];
		}
		Sample s = new Sample();
		float value = Float.NaN;
		if (!modelColumn(x, z, s)) {
			int real = this.generator.getBaseHeight(x, z, Heightmap.Types.OCEAN_FLOOR_WG, this.heights, this.randomState);
			int d = real - s.ground;
			if (Math.abs(d) <= MAX_CORRECTION) {
				value = d;
			}
		}
		cache.keys[slot] = key;
		cache.values[slot] = value;
		return value;
	}

	@Override
	public String describe() {
		return this.correct ? "Expanse terrain model, corrected on an 8-block grid" : "Expanse terrain model";
	}
}
