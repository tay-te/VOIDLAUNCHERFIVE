package dev.voidmc.hearth.sim.terrain;

import dev.voidmc.expanse.world.terrain.CavernModel;
import dev.voidmc.expanse.world.terrain.EarthChunkGenerator;
import dev.voidmc.hearth.api.UndergroundProbe;
import java.util.ArrayList;
import java.util.List;
import net.minecraft.core.BlockPos;
import net.minecraft.server.level.ServerLevel;
import org.jspecify.annotations.Nullable;

/**
 * The open spaces under an Expanse Earth world, read from its cavern model (docs/LIVING_WORLD.md §8.2): the realms —
 * landscapes 110–440 blocks across under vaults up to 130 high — and the great tunnels and passages between them, all
 * decided per column from the seed, so nothing is generated to answer. Thread-safe (the model caches per thread).
 *
 * <p>Only loaded when Expanse is: {@link Undergrounds} names it behind {@code isModLoaded("expanse")} and returns the
 * interface type.
 */
public final class ExpanseUnderground implements UndergroundProbe, dev.voidmc.hearth.sim.land.GreatMines.Provider {
	/** The cavern model's realm cell: at most one realm per 640 × 640 blocks (CavernModel.HALL_CELL, package private). */
	private static final int REALM_CELL = 640;
	/** The realms' characters by the model's theme number, named as Expanse names their biomes ({@code expanse:realm_<name>}). */
	private static final String[] CHARACTERS = {"wilds", "lush", "dripstone", "crystal", "ember", "mere", "frozen", "roots", "fossil", "tidal",
		"amber", "brimstone"};

	private final CavernModel caverns;
	private final ExpanseGreatMines mines;

	private ExpanseUnderground(CavernModel caverns) {
		this.caverns = caverns;
		this.mines = new ExpanseGreatMines(caverns);
	}

	@Override
	public dev.voidmc.hearth.sim.land.GreatMines.Source greatMines() {
		return this.mines;
	}

	/**
	 * The cavern water under (x, z) near {@code floorY} (docs/LIVING_WORLD_2.md §6.1): a realm's mere or the buried sea, an
	 * underground river's surface — where deep towns' landings and boats lie. Lava is no water. Read from the model, as
	 * Expanse's own {@code ExpanseUnderground.water} reads it.
	 */
	@Override
	public int waterY(int x, int z, int floorY) {
		CavernModel.Info c = this.caverns.info(x, z);
		if (c.hall && c.hallEdge > 0 && c.lake > c.floor && !c.lava) {
			int top = (int) Math.floor(c.lake);
			if (Math.abs(top - floorY) <= 24) {
				return top;
			}
		}
		if (c.riverOn && !c.riverFalls && c.riverWater > -900 && c.riverDist <= c.riverHalfWidth) {
			int top = c.waterTop();
			if (Math.abs(top - floorY) <= 24) {
				return top;
			}
		}
		return dev.voidmc.hearth.api.TerrainProbe.NO_WATER;
	}

	/** The probe for a level generated by Expanse's Earth terrain, or null. */
	public static @Nullable UndergroundProbe tryCreate(ServerLevel level) {
		if (level.getChunkSource().getGenerator() instanceof EarthChunkGenerator earth) {
			return new ExpanseUnderground(earth.model(level.getChunkSource().randomState()).caverns());
		}
		return null;
	}

	public static String character(int theme) {
		return theme >= 0 && theme < CHARACTERS.length ? CHARACTERS[theme] : "dripstone";
	}

	@Override
	public @Nullable Realm realm(int x, int z) {
		CavernModel.Info info = this.caverns.info(x, z);
		if (!info.hall || info.hallEdge <= 0) {
			return null;
		}
		int hx = info.hallX;
		int hz = info.hallZ;
		return realmOf(Math.floorDiv(hx, REALM_CELL), Math.floorDiv(hz, REALM_CELL));
	}

	@Override
	public List<Realm> realmsNear(int x, int z, int radius) {
		List<Realm> out = new ArrayList<>();
		int c0x = Math.floorDiv(x - radius, REALM_CELL);
		int c1x = Math.floorDiv(x + radius, REALM_CELL);
		int c0z = Math.floorDiv(z - radius, REALM_CELL);
		int c1z = Math.floorDiv(z + radius, REALM_CELL);
		long r2 = (long) radius * radius;
		for (int cx = c0x; cx <= c1x; cx++) {
			for (int cz = c0z; cz <= c1z; cz++) {
				Realm r = realmOf(cx, cz);
				if (r == null) {
					continue;
				}
				long dx = r.center().getX() - x;
				long dz = r.center().getZ() - z;
				if (dx * dx + dz * dz <= r2) {
					out.add(r);
				}
			}
		}
		out.sort(java.util.Comparator.comparingLong(r -> {
			long dx = r.center().getX() - x;
			long dz = r.center().getZ() - z;
			return dx * dx + dz * dz;
		}));
		return out;
	}

	private @Nullable Realm realmOf(int cx, int cz) {
		CavernModel.Hall h = this.caverns.hall(cx, cz);
		if (!h.exists()) {
			return null;
		}
		CavernModel.Info centre = this.caverns.info(h.x(), h.z());
		int floor = (int) Math.ceil(h.floor());
		int ceiling = centre.hall ? (int) Math.floor(centre.roof) : (int) Math.floor(h.base() + h.height());
		long id = (long) cx << 32 ^ cz & 0xFFFF_FFFFL;
		return new Realm(id, new BlockPos(h.x(), floor, h.z()), (int) h.radius(), floor, ceiling, character(h.theme()));
	}

	@Override
	public int floorY(int x, int z, int nearY) {
		CavernModel.Info c = this.caverns.info(x, z);
		int best = Integer.MIN_VALUE;
		int bestD = Integer.MAX_VALUE;
		if (c.hall && c.hallEdge > 0 && c.pillar > 0 && c.roof > c.floor + 2) {
			// the realm's floor, or the surface of its lake where it has one
			best = (int) Math.ceil(Math.max(c.floor, c.liquid()));
			bestD = Math.abs(best - nearY);
		}
		if (c.tunnel) {
			int f = (int) Math.ceil(c.tunnelFloor);
			if (Math.abs(f - nearY) < bestD) {
				best = f;
				bestD = Math.abs(f - nearY);
			}
		}
		if (c.river && !c.riverFalls) {
			// a river tunnel's walkable floor is its water's surface or its banks: the water top
			int f = c.waterTop();
			if (Math.abs(f - nearY) < bestD) {
				best = f;
				bestD = Math.abs(f - nearY);
			}
		}
		for (CavernModel.Passage p : c.passages) {
			if (p.on && p.dist < p.halfWidth) {
				int f = (int) Math.ceil(p.floor);
				if (Math.abs(f - nearY) < bestD) {
					best = f;
					bestD = Math.abs(f - nearY);
				}
			}
			if (p.chamber && p.chamberIn > 0) {
				int f = (int) Math.ceil(p.chamberFloor);
				if (Math.abs(f - nearY) < bestD) {
					best = f;
					bestD = Math.abs(f - nearY);
				}
			}
		}
		return best;
	}

	@Override
	public int ceilingY(int x, int z, int floorY) {
		CavernModel.Info c = this.caverns.info(x, z);
		int best = Integer.MIN_VALUE;
		if (c.hall && c.hallEdge > 0 && Math.abs((int) Math.ceil(c.floor) - floorY) <= 3) {
			best = (int) Math.floor(c.roof);
		}
		if (best == Integer.MIN_VALUE && c.tunnel && Math.abs((int) Math.ceil(c.tunnelFloor) - floorY) <= 3) {
			best = (int) Math.floor(c.tunnelFloor + c.tunnelHeight);
		}
		if (best == Integer.MIN_VALUE && c.river && Math.abs(c.waterTop() - floorY) <= 3) {
			best = (int) Math.floor(c.tunnelRoof);
		}
		if (best == Integer.MIN_VALUE) {
			for (CavernModel.Passage p : c.passages) {
				if (p.chamber && p.chamberIn > 0 && Math.abs((int) Math.ceil(p.chamberFloor) - floorY) <= 3) {
					best = (int) Math.floor(p.chamberRoof);
					break;
				}
				if (p.on && p.dist < p.halfWidth && Math.abs((int) Math.ceil(p.floor) - floorY) <= 3) {
					float across = Math.min(1, p.dist / p.halfWidth);
					best = (int) Math.floor(p.floor + p.height * (0.35F + 0.65F * (float) Math.sqrt(1 - across * across)));
					break;
				}
			}
		}
		return best;
	}
}
