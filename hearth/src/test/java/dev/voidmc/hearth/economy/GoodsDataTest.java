package dev.voidmc.hearth.economy;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import dev.voidmc.hearth.api.Culture;
import dev.voidmc.hearth.api.Goods;
import dev.voidmc.hearth.api.JobType;
import dev.voidmc.hearth.api.Station;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;
import org.junit.jupiter.api.Test;

/**
 * The economy's data covers every goods (docs/LIVING_WORLD.md §7.5): a name, a word, an item tag, a unit value, a
 * fallback value, default wares, a speciality in every culture; and every shop names real goods. Read from the source
 * tree (generated by tools/economy/gen_data.py), so a goods added to the api without data fails here.
 */
class GoodsDataTest {
	private static final Path RES = Path.of("src/main/resources");
	private static final Path DATA = RES.resolve("data/hearth");

	private static JsonObject json(Path p) throws IOException {
		return JsonParser.parseString(Files.readString(p, StandardCharsets.UTF_8)).getAsJsonObject();
	}

	@Test
	void everyGoodsHasItsNamesTagAndValues() throws IOException {
		JsonObject lang = json(RES.resolve("assets/hearth/lang/en_us/economy.json"));
		JsonObject goods = json(DATA.resolve("hearth_prices/goods.json"));
		for (Goods g : Goods.VALUES) {
			String n = g.getSerializedName();
			assertTrue(lang.has(g.translationKey()), "name of " + n);
			assertTrue(lang.has("hearth.economy.goods." + n), "word for " + n);
			assertTrue(lang.has("tag.item.hearth.goods." + n), "tag name of " + n);
			assertTrue(Files.exists(DATA.resolve("tags/item/goods/" + n + ".json")), "item tag of " + n);
			assertTrue(goods.getAsJsonObject("units").has(n), "unit value of " + n);
			assertTrue(goods.getAsJsonObject("units").get(n).getAsDouble() > 0, "positive unit value of " + n);
			assertTrue(goods.getAsJsonObject("defaults").has(n), "fallback value of " + n);
			assertTrue(goods.getAsJsonObject("wares").has(n), "default wares of " + n);
		}
	}

	@Test
	void everyCultureHasASpecialityForEveryGoods() throws IOException {
		for (Culture c : Culture.values()) {
			Path p = DATA.resolve("hearth_prices/cultures/" + c.getSerializedName() + ".json");
			assertTrue(Files.exists(p), "market of " + c.getSerializedName());
			JsonObject spec = json(p).getAsJsonObject("speciality");
			for (Goods g : Goods.VALUES) {
				assertTrue(spec.has(g.getSerializedName()), c.getSerializedName() + " says nothing of " + g.getSerializedName());
				double v = spec.get(g.getSerializedName()).getAsDouble();
				assertTrue(v > 0.3 && v < 2.5, c.getSerializedName() + "/" + g.getSerializedName() + " = " + v);
			}
			for (Map.Entry<String, JsonElement> e : json(p).getAsJsonObject("wares").entrySet()) {
				assertTrue(Goods.CODEC.byName(e.getKey()) != null, c.getSerializedName() + " sells unknown goods " + e.getKey());
			}
		}
	}

	@Test
	void shopsNameRealGoodsAndRealJobs() throws IOException {
		JsonObject shops = json(DATA.resolve("hearth_prices/shops.json"));
		Set<String> goods = new HashSet<>();
		for (Goods g : Goods.VALUES) {
			goods.add(g.getSerializedName());
		}
		goods.add("*");
		for (String section : new String[]{"workplaces", "jobs"}) {
			for (Map.Entry<String, JsonElement> e : shops.getAsJsonObject(section).entrySet()) {
				if (section.equals("jobs")) {
					assertTrue(JobType.CODEC.byName(e.getKey()) != null, "no job " + e.getKey());
				}
				e.getValue().getAsJsonArray().forEach(el -> assertTrue(goods.contains(el.getAsString()), e.getKey() + ": " + el.getAsString()));
			}
		}
		assertTrue(shops.getAsJsonObject("workplaces").has("commerce/market_stall"));
		assertTrue(shops.getAsJsonObject("jobs").has("fence"));
	}

	@Test
	void everyStationEarnsAWage() {
		for (Station s : Station.values()) {
			assertTrue(EconomyConfig.Households.DEFAULTS.wage(s) > 0, s.getSerializedName());
		}
		assertTrue(EconomyConfig.Households.DEFAULTS.wage(Station.LORD) > EconomyConfig.Households.DEFAULTS.wage(Station.POOR));
	}

	@Test
	void theConfigSurvivesItsOwnFile() {
		var json = EconomyConfig.CODEC.encodeStart(com.mojang.serialization.JsonOps.INSTANCE, EconomyConfig.DEFAULTS).getOrThrow();
		EconomyConfig back = EconomyConfig.CODEC.parse(com.mojang.serialization.JsonOps.INSTANCE, json).getOrThrow();
		assertEquals(EconomyConfig.DEFAULTS.households(), back.households());
		assertEquals(EconomyConfig.DEFAULTS.haggle(), back.haggle());
		assertEquals(EconomyConfig.DEFAULTS.works(), back.works());
		assertEquals(EconomyConfig.DEFAULTS.pricing(), back.pricing());
		EconomyConfig empty = EconomyConfig.CODEC.parse(com.mojang.serialization.JsonOps.INSTANCE, new JsonObject()).getOrThrow();
		assertEquals(EconomyConfig.DEFAULTS.shops(), empty.shops(), "an old file without the new sections gets the defaults");
		assertTrue(empty.service("inn_bed") > 0);
	}
}
